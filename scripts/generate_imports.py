#!/usr/bin/env python3
"""Generate the exhaustive library root and optional thematic import facades."""
import argparse
from pathlib import Path
import sys

from library_sources import module_name, source_modules

ROOT = Path(__file__).resolve().parents[1]
# Example clients are enrolled at the root without a generated family facade.
# Existing facades opt into generator ownership only through this exact marker.
EXCLUDED_FAMILIES = {'Examples'}
GENERATED_MARKER = '-- Generated by scripts/generate_imports.py; do not edit by hand.\n'


def family_facades(root: Path) -> set[Path]:
    """Discover current family surfaces without a per-family enrollment registry."""
    return {Path('Quillen') / (path.name + '.lean')
            for path in (root / 'Quillen').iterdir()
            if path.is_dir() and path.name not in EXCLUDED_FAMILIES
            and not path.name.startswith('.')}


def render_imports(modules: list[str], description: str) -> str:
    return (GENERATED_MARKER
            + '\n'.join('import ' + module for module in sorted(modules))
            + '\n\n/-!\n' + description + '\n-/\n')


def generated_files(root: Path) -> dict[Path, str]:
    """Existing implementations are discovered; only these facades are managed."""
    modules = source_modules(root) - {Path('Quillen.lean')}
    outputs = {}
    for facade in sorted(family_facades(root)):
        family = facade.stem
        directory = Path('Quillen') / family
        if (root / facade).exists() and not (root / facade).read_text().startswith(GENERATED_MARKER):
            # The existing source is manually owned. It remains enrolled at the
            # exhaustive root, but generation must not take over its contents.
            continue
        outputs[facade] = render_imports(
            [module_name(path) for path in modules if directory in path.parents],
            f'# {family}\n\nAll modules in the `Quillen.{family}` family.\n'
            'Use an individual module import for a smaller dependency closure.')
        modules.add(facade)
    outputs[Path('Quillen.lean')] = render_imports(
        [module_name(path) for path in modules],
        '# Quillen library\n\nThe exhaustive import surface for all project source modules.\n'
        'Use thematic facades or individual module imports for smaller dependencies.')
    return outputs


def stale_files(root: Path) -> list[Path]:
    return [path for path, expected in generated_files(root).items()
            if not (root / path).is_file() or (root / path).read_text() != expected]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated imports are stale')
    parser.add_argument('--root', type=Path, default=ROOT, help='project root (defaults to this checkout)')
    args = parser.parse_args()
    outputs = generated_files(args.root)
    if args.check:
        stale = stale_files(args.root)
        if stale:
            print('Stale generated imports: ' + ', '.join(map(str, stale))
                  + '\nRun python3 scripts/generate_imports.py', file=sys.stderr)
            return 1
    else:
        # Recheck ownership before any writes: another editor may have created
        # or taken over a family facade after discovery.
        conflicts = [path for path in outputs if path != Path('Quillen.lean')
                     and (args.root / path).exists()
                     and not (args.root / path).read_text().startswith(GENERATED_MARKER)]
        if conflicts:
            print('Refusing to overwrite manually owned facades: '
                  + ', '.join(map(str, conflicts)), file=sys.stderr)
            return 1
        for path, content in outputs.items():
            (args.root / path).write_text(content)
    print(f'Generated imports {"checked" if args.check else "written"}: '
          f'{len(outputs)} files; {len(source_modules(args.root))} source modules.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
