class ClientScopeTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix='quillen-client-scope-')
        self.root = Path(self.tmp.name)
        (self.root / 'Quillen').mkdir()
        self.write('Quillen.lean', '')
        self.write('examples/downstream/Consumer/Shared.lean',
                   'module\npublic import Quillen\nprivate def hidden := 1\n')
        self.write('examples/downstream/Consumer/Use.lean',
                   'module\npublic import Consumer.Shared\ntheorem result : True := by trivial\n')
        self.write('examples/downstream/Consumer/PublicLibraries.lean',
                   'module\npublic import Aglib\npublic import Quillen\n@[expose] public section\n')
        self.regenerate()

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, name, source):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source)

    def regenerate(self):
        path = Path('examples/downstream/Consumer.lean')
        self.write(path, generated_files(self.root)[path])

    def test_generated_facade_certification_keeps_all_selected_text_and_origin_union(self):
        scope = client_check_scope(self.root, ['Consumer', 'Consumer.Use'], batch_size=1)
        self.assertEqual(scope['environment_batches'], [['Consumer.Use']])
        self.assertEqual(scope['facade_text_modules'], ['Consumer'])
        self.assertEqual(scope['audit_defining_origin_modules'],
                         ['Consumer.Shared', 'Consumer.Use'])
        self.assertEqual(scope['audit_origin_union'], ['Consumer.Shared', 'Consumer.Use'])
        self.assertEqual(scope['audit_origin_overlaps'], {'Consumer.Shared': [0, 1]})
        self.assertEqual(set(scope['facade_certificates']),
                         {'Consumer', 'Consumer.PublicLibraries'})
        self.assertEqual(scope['facade_certificates']['Consumer']['kind'],
                         'generator-and-source-certified-import-only')
        self.assertEqual(set(scope['selected_lint_modules']),
                         set(sum(scope['environment_batches'], []) + scope['facade_text_modules']))

    def test_dependency_generator_shadow_cannot_replace_trusted_generator(self):
        shadow = types.ModuleType('generate_imports')
        shadow.generated_files = lambda root: {}
        shadow.generator_owned = lambda source: True
        with patch.dict(sys.modules, {'generate_imports': shadow}):
            scope = client_check_scope(self.root, ['Consumer'])
        self.assertEqual(scope['facade_certificates']['Consumer']['kind'],
                         'generator-and-source-certified-import-only')
        self.assertEqual(scope['audit_origin_union'], ['Consumer.Shared', 'Consumer.Use'])

    def test_stale_generated_root_cannot_hide_an_origin(self):
        path = self.root / 'examples/downstream/Consumer.lean'
        path.write_text(path.read_text().replace('public import Consumer.Shared\n', ''))
        with self.assertRaisesRegex(ValueError, 'differs from current generator'):
            client_check_scope(self.root, ['Consumer'])

    def test_commands_cannot_be_misclassified_as_vacuous_imports(self):
        for command in ['private def datum := 1', 'export Quillen (datum)',
                        'initialize pure ()', '#eval 1', 'theorem fact : True := by trivial']:
            with self.subTest(command=command):
                self.write('examples/downstream/Consumer/Manual.lean',
                           'module\nimport Quillen\n' + command + '\n')
                scope = client_check_scope(self.root, ['Consumer.Manual'])
                self.assertEqual(scope['environment_batches'], [['Consumer.Manual']])
                self.assertEqual(scope['facade_text_modules'], [])
                self.assertEqual(scope['audit_origin_union'], ['Consumer.Manual'])

    def test_quoted_or_documented_marker_is_not_a_generator_certificate(self):
        self.write('examples/downstream/Consumer.lean',
                   '/- -- Generated by scripts/generate_imports.py; do not edit by hand. -/\n'
                   'import Consumer.Use\n')
        with self.assertRaisesRegex(ValueError, 'Untrusted generated'):
            client_check_scope(self.root, ['Consumer'])

    def test_missing_source_cycle_and_redirect_fail_closed(self):
        self.write('examples/downstream/Consumer/Bad.lean', 'import Consumer.Missing\n')
        with self.assertRaisesRegex(ValueError, 'Missing or redirected'):
            client_check_scope(self.root, ['Consumer.Bad'])
        self.write('examples/downstream/Consumer/Bad.lean', 'import Consumer.Other\n')
        self.write('examples/downstream/Consumer/Other.lean', 'import Consumer.Bad\n')
        with self.assertRaisesRegex(ValueError, 'Cyclic'):
            client_check_scope(self.root, ['Consumer.Bad'])
        outside = self.root / 'outside.lean'
        outside.write_text('def hidden := 1\n')
        (self.root / 'examples/downstream/Consumer/Redirect.lean').symlink_to(outside)
        with self.assertRaisesRegex(ValueError, 'redirected'):
            client_check_scope(self.root, ['Consumer.Redirect'])

    def test_bounded_audit_batches_cover_unselected_reachable_private_modules(self):
        for index in range(19):
            self.write(f'examples/downstream/Consumer/Extra{index}.lean',
                       f'module\nimport Consumer.Shared\nprivate def extra{index} := 1\n')
        self.regenerate()
        scope = client_check_scope(self.root, ['Consumer'], batch_size=4)
        self.assertTrue(all(len(batch) <= 4 for batch in scope['audit_batches']))
        self.assertEqual(len(scope['audit_origin_union']), 21)
        self.assertIn('Consumer.Extra18', scope['audit_origin_union'])
        self.assertIn('Consumer.Shared', scope['audit_origin_overlaps'])
        with self.assertRaises(ValueError):
            client_check_scope(self.root, ['Consumer'], batch_size=0)

    def test_text_adaptation_keeps_native_text_predicates_and_exclusions(self):
        original = (ROOT / 'Tools/LintScoped.lean').read_text()
        adapted = scoped_lint_source(original, text_only=True)
        self.assertNotIn('(modules.push `Batteries.Tactic.Lint', adapted)
        marker = '  let styleOptions : Lean.Linter.LinterOptions'
        self.assertEqual(original[original.index(marker):], adapted[adapted.index(marker):])
        self.assertIn('getChecks (slow := true) (runOnly := none) (runAlways := none)', adapted)
        self.assertIn('let exclusions ← readExclusions', adapted)
        with self.assertRaisesRegex(ValueError, 'interface changed'):
            scoped_lint_source(original.replace('if decls.isEmpty then', 'if false then'))


class NativeOutputTests(unittest.TestCase):
    def test_merge_keeps_one_header_and_every_provider_test_and_client_mapping(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            mappings = []
            for index, phase in enumerate(('provider', 'test', 'client')):
                path = root / (phase + '.jsonl')
                path.write_text(f'"2026-03-17"\n[{index},"{index:016x}.ltar"]\n')
                mappings.append(path)
            output = root / 'export/outputs.jsonl'
            merge_native_outputs(mappings, output)
            self.assertEqual(output.read_text(), '"2026-03-17"\n' + ''.join(
                f'[{index},"{index:016x}.ltar"]\n' for index in range(3)))

    def test_bad_header_or_row_fails_before_publishing_an_output(self):
        for text in ('', '"older-format"\n', '"2026-03-17"\n"2026-03-17"\n',
                     '"2026-03-17"\n[1]\n', '"2026-03-17"\ninvalid\n'):
            with self.subTest(text=text), tempfile.TemporaryDirectory() as temporary:
                root = Path(temporary)
                mapping = root / 'bad.jsonl'
                mapping.write_text(text)
                output = root / 'outputs.jsonl'
                with self.assertRaises(ValueError):
                    merge_native_outputs([mapping], output)
                self.assertFalse(output.exists())


class SchedulingTests(unittest.TestCase):
    def test_parallel_jobs_are_bounded_and_every_disjoint_check_finishes(self):
        lock = threading.Lock()
        state = {'active': 0, 'peak': 0}
        completed = []

        def check(index):
            with lock:
                state['active'] += 1
                state['peak'] = max(state['peak'], state['active'])
            time.sleep(0.01)
            with lock:
                completed.append(index)
                state['active'] -= 1

        parallel_checks([partial(check, index) for index in range(19)], 7)
        self.assertEqual(sorted(completed), list(range(19)))
        self.assertGreater(state['peak'], 1)
        self.assertLessEqual(state['peak'], 7)
        for jobs in [0, 8]:
            with self.assertRaises(ValueError):
                parallel_checks([], jobs)

    def test_failure_is_propagated_only_after_already_dispatched_checks_settle(self):
        completed = []

        def check(index):
            time.sleep(0.01)
            completed.append(index)
            if index == 0:
                raise RuntimeError('failed check')

        with self.assertRaisesRegex(RuntimeError, 'failed check'):
            parallel_checks([partial(check, index) for index in range(9)], 7)
        self.assertEqual(sorted(completed), list(range(9)))



class SourceLintPolicyTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix='quillen-source-lint-')
        self.root = Path(self.tmp.name).resolve()
        self.calls = []
        sources = {
            'Quillen/A.lean': 'def a := 1\n',
            'Quillen/Dependent.lean': 'import Quillen.A\ndef dependent := a\n',
            'Quillen.lean': 'import Quillen.A Quillen.Dependent\n',
            'QuillenTest/Changed.lean': 'import Quillen.A\nexample : True := trivial\n',
            'QuillenTest/Dependent.lean': 'import Quillen.Dependent\nexample : True := trivial\n',
            'QuillenTest/Axioms.lean': 'import Quillen\n-- audit\n',
            'examples/downstream/Consumer/Shared.lean': 'def shared := 1\n',
            'examples/downstream/Consumer/Changed.lean': 'import Consumer.Shared\ndef changed := shared\n',
            'examples/downstream/Consumer/Dependent.lean': 'import Consumer.Changed\ndef dependent := changed\n',
            'examples/downstream/Consumer.lean': 'import Consumer.Changed Consumer.Dependent\n',
            'examples/downstream/Audit.lean': 'import Consumer\n-- audit\n',
        }
        for name, source in sources.items():
            target = self.root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(source)
        (self.root / 'Tools').mkdir()
        (self.root / 'Tools/LintScoped.lean').write_bytes((ROOT / 'Tools/LintScoped.lean').read_bytes())
        (self.root / '.lake/packages').mkdir(parents=True)
        self.plan = dict(schema=1, lean=True, full=False, base=None, trust=True, client_trust=True,
            providers=['Quillen.A', 'Quillen.Dependent'],
            provider_batches=[['Quillen.A'], ['Quillen.Dependent']],
            tests=['QuillenTest.Changed', 'QuillenTest.Dependent'],
            clients=['Consumer', 'Consumer.Changed', 'Consumer.Dependent'],
            changed=['Quillen/A.lean', 'QuillenTest/Changed.lean',
                     'examples/downstream/Consumer/Changed.lean', 'examples/downstream/Consumer.lean'])

    def tearDown(self):
        self.tmp.cleanup()

    def run_stub(self, plan):
        original = copy.deepcopy(plan)
        directory = self.root / 'verification'
        def run(command, **kwargs):
            self.calls.append(list(command))
        with patch('check_run.subprocess.run', side_effect=run), patch.dict(os.environ, {
                'QUILLEN_VERIFY_DIR': str(directory), 'QUILLEN_CHECK_JOBS': '1'}):
            execute(self.root, plan)
        self.assertEqual(plan, original)
        return directory

    def linted_modules(self):
        return [module for command in self.calls if '--run' in command
                for module in command[command.index('--run') + 2:]]

    def test_changed_sources_lint_unchanged_consumers_only_build_and_full_audits_remain(self):
        original_scope = client_check_scope(self.root, self.plan['clients'])
        directory = self.run_stub(self.plan)
        self.assertEqual(set(self.linted_modules()),
                         {'Quillen.A', 'QuillenTest.Changed', 'Consumer.Changed', 'Consumer'})
        self.assertIn(['lake', 'build', 'Quillen.Dependent'], self.calls)
        self.assertIn(['lake', 'build', *self.plan['tests']], self.calls)
        self.assertIn(['lake', 'build', *self.plan['clients']], self.calls)
        scope = json.loads((directory / 'client-scope.json').read_text())
        for field in ['audit_batches', 'audit_batch_origin_closures', 'audit_origin_union']:
            self.assertEqual(scope[field], original_scope[field])
        self.assertEqual(scope['audit_origin_union'],
                         ['Consumer.Changed', 'Consumer.Dependent', 'Consumer.Shared'])
        self.assertEqual(scope['selected_lint_modules'], ['Consumer', 'Consumer.Changed'])
        self.assertIn('import Quillen.Dependent\n', (directory / 'axioms.lean').read_text())
        audits = ''.join(path.read_text() for path in directory.glob('client-audit*.lean'))
        self.assertTrue(all('import ' + module + '\n' in audits
                            for module in original_scope['audit_origin_union']))
        self.assertTrue(any('--run' not in command and command[-1].endswith('client-audit.lean')
                            for command in self.calls))

    def test_no_changed_lean_sources_runs_no_linter_but_keeps_builds_and_audits(self):
        self.plan['changed'] = ['lake-manifest.json', 'CONTRIBUTING.md']
        directory = self.run_stub(self.plan)
        self.assertEqual(self.linted_modules(), [])
        self.assertFalse(any('Batteries.Tactic.Lint' in command for command in self.calls))
        self.assertTrue((directory / 'axioms.lean').is_file())
        self.assertTrue((directory / 'client-audit.lean').is_file())
        self.assertIn(['lake', 'build', 'Quillen.Dependent'], self.calls)

    def test_comprehensive_initial_and_legacy_plans_preserve_conservative_lint_all(self):
        for override in [{'full': True}, {'base': 'EMPTY_TREE'}, {'legacy': True}]:
            plan = dict(self.plan, changed=[])
            if 'legacy' in override:
                del plan['changed']
            else:
                plan.update(override)
            self.assertIsNone(source_lint_scope(self.root, plan))
        del self.plan['changed']
        self.run_stub(self.plan)
        self.assertIn('Quillen.Dependent', self.linted_modules())
        self.assertIn('Consumer.Dependent', self.linted_modules())

    def test_changed_paths_are_valid_unique_classified_and_deleted_sources_are_excluded(self):
        for paths in [['Quillen/A.lean', 'Quillen/A.lean'], ['../Quillen/A.lean'],
                      ['/Quillen/A.lean'], ['Quillen//A.lean'], ['Other/A.lean'], [None]]:
            with self.subTest(paths=paths), self.assertRaises(ValueError):
                source_lint_scope(self.root, dict(self.plan, changed=paths))
        scope = source_lint_scope(self.root, dict(self.plan, changed=[
            'Quillen/Removed.lean', 'Quillen/A.lean', 'Quillen.lean',
            'QuillenTest/Axioms.lean', 'Tools/LintScoped.lean', 'lake-manifest.json']))
        self.assertEqual(scope, {'Quillen', 'Quillen.A'})
        (self.root / 'Quillen/Redirect.lean').symlink_to('A.lean')
        with self.assertRaises(ValueError):
            source_lint_scope(self.root, dict(self.plan, changed=['Quillen/Redirect.lean']))

    def test_changed_provider_and_test_facades_keep_existing_native_text_checks(self):
        (self.root / 'QuillenTest.lean').write_text('import QuillenTest.Changed\n')
        self.plan['changed'] += ['Quillen.lean', 'QuillenTest.lean']
        self.plan['providers'].append('Quillen')
        self.plan['provider_batches'].append(['Quillen'])
        self.plan['tests'].append('QuillenTest')
        self.run_stub(self.plan)
        self.assertIn('Quillen', self.linted_modules())
        self.assertIn('QuillenTest', self.linted_modules())

    def test_static_scope_still_has_no_lean_or_cache_work(self):
        with patch('check_run.subprocess.run') as run:
            execute(self.root, dict(lean=False, changed=['not/a/module']))
        run.assert_not_called()
        self.assertFalse((self.root / '.lake/verification').exists())


if __name__ == '__main__':
    unittest.main()
