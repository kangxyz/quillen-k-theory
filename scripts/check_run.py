#!/usr/bin/env python3
"""Execute a selected check plan, retaining compatible Lake outputs."""
import argparse
from concurrent.futures import ThreadPoolExecutor
from functools import partial
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

from check_scope import GLOBAL_INPUTS, git, select
from library_sources import is_import_surface, lean_imports, module_path


def chunks(modules, size):
    if size < 1:
        raise ValueError('Check batch size must be positive')
    return [modules[start:start + size] for start in range(0, len(modules), size)]


def client_check_scope(root, modules, batch_size=8):
    """Certify zero-origin surfaces and the complete reachable Consumer-origin union.

    Declaration batches use each entry's real dependency environment, rather
    than unrelated imports contributed only by an exhaustive facade.
    """
    client = (root / 'examples/downstream').resolve()
    graph, certificates, visiting = {}, {}, set()

    def visit(module):
        if module in visiting:
            raise ValueError('Cyclic client import scope: ' + module)
        if module in graph:
            return
        if module != 'Consumer' and not module.startswith('Consumer.'):
            raise ValueError('Client check target is outside Consumer: ' + module)
        path = client / module_path(module)
        if path.is_symlink() or not path.is_file() or not path.resolve().is_relative_to(client):
            raise ValueError('Missing or redirected client check source: ' + module)
        text = path.read_text()
        imports = [name for name in lean_imports(text)
                   if name == 'Consumer' or name.startswith('Consumer.')]
        if is_import_surface(text):
            certificate = {'path': str(path.relative_to(root.resolve())),
                           'source_sha256': hashlib.sha256(text.encode()).hexdigest(),
                           'kind': 'source-certified-import-only', 'own_defining_origins': 0}
            if module == 'Consumer' and '-- Generated by scripts/generate_imports.py;' in text:
                # Guarded CI prepends dependency scripts to sys.path. Load the
                # adjacent trusted generator explicitly, not a same-named helper.
                spec = importlib.util.spec_from_file_location(
                    '_quillen_check_generator', Path(__file__).with_name('generate_imports.py'))
                if spec is None or spec.loader is None:
                    raise ValueError('Trusted client generator is unavailable')
                generator = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(generator)
                if not generator.generator_owned(text):
                    raise ValueError('Untrusted generated client facade marker')
                if generator.generated_files(root).get(Path('examples/downstream/Consumer.lean')) != text:
                    raise ValueError('Generated client facade differs from current generator')
                certificate['kind'] = 'generator-and-source-certified-import-only'
            certificates[module] = certificate
        visiting.add(module)
        # Insert only after recursion so cycles cannot masquerade as cached nodes.
        for dependency in imports:
            visit(dependency)
        visiting.remove(module)
        graph[module] = imports

    selected = list(dict.fromkeys(modules))
    for module in selected:
        visit(module)
    defining = [module for module in selected if module not in certificates]
    facades = [module for module in selected if module in certificates]
    origins = sorted(set(graph) - certificates.keys())
    audit_batches = chunks(origins, batch_size)

    def closure(entries):
        seen, pending = set(), list(entries)
        while pending:
            module = pending.pop()
            if module not in seen:
                seen.add(module); pending.extend(graph[module])
        return sorted(seen - certificates.keys())

    audit_closures = [closure(batch) for batch in audit_batches]
    union = set().union(*(set(batch) for batch in audit_closures)) if audit_closures else set()
    if union != set(origins):
        raise ValueError('Client audit batching lost defining-origin coverage')
    overlaps = {module: [index for index, batch in enumerate(audit_closures) if module in batch]
                for module in origins}
    overlaps = {module: indices for module, indices in overlaps.items() if len(indices) > 1}
    if set(defining) | set(facades) != set(selected) or set(defining) & set(facades):
        raise ValueError('Client lint batching lost selected-target coverage')
    return {'selected_lint_modules': selected,
            'environment_batches': chunks(defining, batch_size),
            'facade_text_modules': facades, 'facade_certificates': certificates,
            'audit_defining_origin_modules': origins, 'audit_batches': audit_batches,
            'audit_batch_origin_closures': audit_closures,
            'audit_origin_union': sorted(union), 'audit_origin_overlaps': overlaps,
            'environment_boundary': 'Each declaration batch loads real dependencies; '
                                    'unrelated pure-facade-only imports are omitted.'}


def scoped_lint_source(text, *, text_only=False):
    guard = ('    if decls.isEmpty then\n'
             '      throwError "Selected modules define no declarations; specify defining leaf modules"\n')
    if text.count(guard) != 1:
        raise ValueError('Scoped linter interface changed; review empty-facade adaptation')
    text = text.replace(guard, '')
    if text_only:
        marker = '(modules.push `Batteries.Tactic.Lint'
        if text.count(marker) != 1:
            raise ValueError('Scoped linter imports changed; review facade text adaptation')
        # Called only for source-certified zero-origin facades. Keep all default
        # declaration checks (vacuous here), exclusions and native text predicates.
        text = text.replace(marker, '((#[] : Array Name).push `Batteries.Tactic.Lint')
    return text


def parallel_checks(calls, jobs):
    if not 1 <= jobs <= 7:
        raise ValueError('Concurrent check jobs must be between 1 and 7')
    if jobs == 1:
        for call in calls:
            call()
    else:
        # Every call owns a temporary toolchain, process group and distinct receipt.
        # Executor shutdown waits for all already-dispatched groups before raising.
        with ThreadPoolExecutor(max_workers=jobs) as pool:
            futures = [pool.submit(call) for call in calls]
            for future in futures:
                future.result()


def batch_phase(phase, index, count):
    return phase if count == 1 else f'{phase}-{index}'


def execute(root, plan, *, ci=False, rehash=False, output=None):
    if not plan['lean']:
        print('Static scope: no Lean, dependency cache, or native cache work selected.')
        return
    aglib = root / '.lake/packages/Aglib/scripts'
    if ci and not all((aglib / name).is_file() for name in ('build_serial.py', 'resource_guard.py')):
        raise ValueError('Resolve the pinned Aglib dependency before guarded CI checks')
    requested = os.environ.get('QUILLEN_VERIFY_DIR')
    if requested:
        directory = Path(requested)
        if not directory.is_absolute():
            directory = root / directory
        if directory.exists():
            raise ValueError('Use a fresh QUILLEN_VERIFY_DIR for each check invocation')
        directory.mkdir(parents=True, exist_ok=False)
    else:
        (root / '.lake/verification').mkdir(parents=True, exist_ok=True)
        directory = Path(tempfile.mkdtemp(prefix='checks-', dir=root / '.lake/verification'))
    (directory / 'scope.json').write_text(json.dumps(plan, indent=2) + '\n')
    lake = ['lake'] + (['--rehash'] if rehash else [])
    if ci:
        sys.path.insert(0, str(aglib))
        from build_serial import build_threads, capped_toolchain
        from resource_guard import limits, run

    def safe(phase, command, cwd=root):
        print(f'{phase}: {" ".join(command)}', flush=True)
        if not ci:
            subprocess.run(command, cwd=cwd, check=True)
            return
        budget = limits()
        budget['native_build_threads'] = build_threads()
        with capped_toolchain(cwd, threads=budget['native_build_threads']) as environment:
            command = list(command)
            if command[:3] == ['lake', 'env', 'lean']:
                command[2] = environment['LEAN']
            code = run(command, cwd=cwd, env=environment,
                       receipt=directory / f'{phase}.json', budget=budget)
            if code:
                raise subprocess.CalledProcessError(code, command)

    mappings = []
    lint_runtime_ready = False
    lint_runner = directory / 'LintScoped.lean'
    lint_text = (root / 'Tools/LintScoped.lean').read_text()
    lint_runner.write_text(scoped_lint_source(lint_text))

    def build(phase, modules, cwd=root):
        if not modules:
            return
        if ci:
            mapping = directory / f'{phase}-outputs.jsonl'
            command = [sys.executable, str(aglib / 'build_serial.py'), '--root', str(cwd),
                       '--receipt-dir', str(directory / phase), '--outputs', str(mapping)]
            if rehash:
                command.append('--rehash')
            subprocess.run([*command, *modules], cwd=cwd, check=True)
            mappings.append(mapping)
        else:
            safe(phase, [*lake, 'build', *modules], cwd)

    def lint_runtime():
        nonlocal lint_runtime_ready
        if not lint_runtime_ready:
            safe('lint-runtime', [*lake, 'build', 'Batteries.Tactic.Lint',
                                  'Mathlib.Tactic.Linter.TextBased'])
            lint_runtime_ready = True

    def lint(phase, modules, cwd=root):
        if modules:
            lint_runtime()
            safe(phase, ['lake', 'env', 'lean', '--run', str(lint_runner), *modules], cwd)

    def audit(phase, template, import_name, modules, cwd=root):
        if not modules:
            return
        text = (root / template).read_text()
        marker = f'import {import_name}\n'
        if text.count(marker) != 1:
            raise ValueError(f'Cannot scope changed audit template: {template}')
        scoped = directory / f'{phase}.lean'
        scoped.write_text(text.replace(marker, ''.join(f'import {module}\n' for module in modules)))
        safe(phase, ['lake', 'env', 'lean', '-j2', str(scoped)], cwd)

    for index, modules in enumerate(plan['provider_batches']):
        build(f'providers-{index}', modules)
        lint(f'provider-lint-{index}', modules)
    if plan['full'] or plan['base'] == 'EMPTY_TREE':
        safe('full-native-style', [*lake, 'exe', 'lint-style'])
    if plan['trust']:
        audit('axioms', 'QuillenTest/Axioms.lean', 'Quillen', plan['providers'])
    build('tests', plan['tests'])
    lint('test-lint', plan['tests'])
    # QuillenTest is a lean_lib test driver, with compile-time assertions and no
    # runtime main. A successful selected build (or compatible cached artifact)
    # supplies this coverage. Only explicit comprehensive diagnostics replay it.
    if plan['full']:
        for index, module in enumerate(plan['tests']):
            safe(f'test-{index}', ['lake', 'env', 'lean', '-j2', module.replace('.', '/') + '.lean'])
    if plan['clients']:
        client = root / 'examples/downstream'
        (client / '.lake').mkdir(exist_ok=True)
        packages = client / '.lake/packages'
        if not packages.exists():
            packages.symlink_to(root / '.lake/packages', target_is_directory=True)
        build('client-build', plan['clients'], client)
        scope = client_check_scope(root, plan['clients'])
        (directory / 'client-scope.json').write_text(json.dumps(scope, indent=2) + '\n')
        jobs = int(os.environ.get('QUILLEN_CHECK_JOBS', '1'))
        lint_runtime()
        calls = [partial(safe, batch_phase('client-lint', index,
                          len(scope['environment_batches'])),
                         ['lake', 'env', 'lean', '--run', str(lint_runner), *batch], client)
                 for index, batch in enumerate(scope['environment_batches'])]
        if scope['facade_text_modules']:
            text_runner = directory / 'LintFacadeText.lean'
            text_runner.write_text(scoped_lint_source(lint_text, text_only=True))
            calls.append(partial(safe, 'client-facade-text',
                                ['lake', 'env', 'lean', '--run', str(text_runner),
                                 *scope['facade_text_modules']], client))
        parallel_checks(calls, jobs)
        if plan['client_trust']:
            parallel_checks([partial(audit, batch_phase('client-audit', index,
                                     len(scope['audit_batches'])),
                                     'examples/downstream/Audit.lean', 'Consumer', batch, client)
                             for index, batch in enumerate(scope['audit_batches'])], jobs)
    # Export only successful, verified selected build mappings. No second build
    # and no aggregate roots are introduced at the publication boundary.
    if output:
        if not ci:
            raise ValueError('--native-outputs requires --ci')
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(''.join(path.read_text() for path in mappings))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-only', action='store_true')
    parser.add_argument('--source-checked', action='store_true',
                        help='reuse successful source checks for the same unchanged inputs')
    parser.add_argument('--ci', action='store_true')
    parser.add_argument('--rehash', action='store_true')
    parser.add_argument('--base')
    parser.add_argument('--head')
    parser.add_argument('--full', action='store_true')
    parser.add_argument('--plan', type=Path)
    parser.add_argument('--native-outputs', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    try:
        static_commands = ([sys.executable, 'scripts/generate_imports.py', '--check'],
                        [sys.executable, 'scripts/check_library_layout.py'],
                        [sys.executable, 'scripts/check_placeholders.py'],
                        [sys.executable, '-m', 'unittest', 'discover', '-s', 'scripts', '-p', 'test_*.py'])
        for command in (() if args.source_checked else static_commands):
            subprocess.run(command, cwd=root, check=True)
        if args.source_only:
            return 0
        if args.plan:
            if args.base or args.head or args.full:
                raise ValueError('--plan cannot be combined with --base/--head/--full')
            plan = json.loads(args.plan.read_text())
            if plan['head']:
                modified = git(root, 'diff', '--name-only', plan['revision']).splitlines()
                untracked = git(root, 'ls-files', '--others', '--exclude-standard', '--',
                                'Quillen', 'QuillenTest', 'Tools', 'examples/downstream',
                                *sorted(GLOBAL_INPUTS)).splitlines()
                if git(root, 'rev-parse', 'HEAD').strip() != plan['revision'] or any(
                        path.endswith('.lean') or path in GLOBAL_INPUTS
                        for path in modified + untracked):
                    raise ValueError('Checked-out Lean/check configuration differs from the selected head')
            if plan != select(root, plan['base'], plan['head'], plan['full']):
                raise ValueError('Selected scope is stale; regenerate the plan for these inputs')
        else:
            plan = select(root, args.base, args.head, args.full)
        execute(root, plan, ci=args.ci, rehash=args.rehash or os.environ.get('QUILLEN_REHASH') == '1',
                output=args.native_outputs)
    except subprocess.CalledProcessError as error:
        return error.returncode if error.returncode > 0 else 128 - error.returncode
    except (OSError, ValueError, KeyError) as error:
        print(f'Check failed: {error}', file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
